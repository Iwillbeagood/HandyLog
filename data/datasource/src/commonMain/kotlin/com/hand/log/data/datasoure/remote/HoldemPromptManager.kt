		)
		append("(B) 상대의 액션에 대응(상대의 오픈/림프/3벳에 반응) — 이때만 '이미 액션한 상대'의 레인지와 비교해 설명하세요. ")
		append(
			"포지션별 레인지 폭 규칙은 오직 '이미 액션한 상대'에게만 적용합니다: 상대가 UTG·MP 등 앞 포지션이면 좁고 강해 3벳은 프리미엄 밸류로 제한되고 나머지는 콜·폴드가 낫고, ",
